import { PDFDocument, StandardFonts, rgb, type PDFFont, type PDFPage } from "pdf-lib";
import type { Prisma } from "@digimarket/db";

type InvoicePrint={
 number:string|null;currencyCode:string;sellerName:string;sellerAddress:string;
 sellerTaxId:string|null;buyerName:string;buyerAddress:string|null;
 issuedOn:Date|null;dueOn:Date;notes:string|null;
 subtotal:Prisma.Decimal;taxTotal:Prisma.Decimal;total:Prisma.Decimal;paidTotal:Prisma.Decimal;
 lines:{description:string;quantity:Prisma.Decimal;unitPrice:Prisma.Decimal;
  taxRate:Prisma.Decimal;total:Prisma.Decimal}[];
};
const color=rgb(0.12,0.16,0.24);
const muted=rgb(0.42,0.47,0.55);
const safe=(value:string)=>value.normalize("NFKD").replace(/[^\x20-\x7E]/g,"?");
function wrap(s:string,font:PDFFont,size:number,width:number){
 const words=safe(s).split(/\s+/);const result:string[]=[];let line="";
 for(const word of words){const next=line?line+" "+word:word;
  if(font.widthOfTextAtSize(next,size)<=width){line=next;continue;}
  if(line)result.push(line);
  line="";
  for(const char of word){if(font.widthOfTextAtSize(line+char,size)>width&&line){result.push(line);line=char;}
   else line+=char;}
 }
 if(line)result.push(line);return result.length?result:[""];
}
export async function invoicePdf(i:InvoicePrint){
 const doc=await PDFDocument.create();
 const regular=await doc.embedFont(StandardFonts.Helvetica);
 const bold=await doc.embedFont(StandardFonts.HelveticaBold);
 const W=595,H=842,m=46;
 let page:PDFPage=doc.addPage([W,H]),y=H-55;
 const line=(s:string,x:number,size=10,font:PDFFont=regular,shade=color)=>{
  page.drawText(safe(s),{x,y,size,font,color:shade,maxWidth:W-2*m});
 };
 const horizontal=()=>page.drawLine({start:{x:m,y},end:{x:W-m,y},thickness:0.7,color:rgb(0.83,0.85,0.89)});
 const newPage=()=>{page=doc.addPage([W,H]);y=H-50;line("INVOICE "+(i.number??""),m,12,bold);y-=24;};
 const ensure=(height:number)=>{if(y-height<58)newPage();};
 const section=(label:string)=>{ensure(36);line(label,m,10,bold);y-=17;};
 const paragraph=(s:string,x=m,width=W-2*m,size=10,font:PDFFont=regular)=>{
  for(const t of wrap(s,font,size,width)){ensure(15);line(t,x,size,font);y-=15;}
 };
 page.drawRectangle({x:0,y:H-125,width:W,height:125,color:rgb(0.95,0.96,0.99)});
 line("INVOICE",m,24,bold);y-=30;
 line(i.number??"UNNUMBERED",m,12,bold);y-=20;
 line("Issued: "+(i.issuedOn?.toISOString().slice(0,10)??""),m,10);y-=17;
 line("Due: "+i.dueOn.toISOString().slice(0,10),m,10);y-=34;
 section("FROM");paragraph(i.sellerName);paragraph(i.sellerAddress);
 if(i.sellerTaxId)paragraph("Tax ID (as provided): "+i.sellerTaxId);
 y-=8;section("BILL TO");paragraph(i.buyerName);
 if(i.buyerAddress)paragraph(i.buyerAddress);
 y-=15;horizontal();y-=22;
 line("DESCRIPTION",m,10,bold);line("QTY",338,10,bold);line("RATE",407,10,bold);line("TOTAL",505,10,bold);
 y-=16;horizontal();y-=19;
 for(const item of i.lines){
  const lines=wrap(item.description,regular,9,270);
  ensure(Math.max(lines.length*14,26)+12);
  const at=y;
  for(const t of lines){line(t,m,9);y-=14;}
  const next=y;
  y=at;line(item.quantity.toFixed(2),338,9);line(item.unitPrice.toFixed(2),405,9);
  line(item.total.toFixed(2),503,9);y=next-16;
  if(item.taxRate.gt(0)){line("Tax: "+item.taxRate.toFixed(2)+"%",m+10,8,regular,muted);y-=16;}
 }
 ensure(130);y-=8;horizontal();y-=26;
 line("Subtotal",365,11,regular,muted);line("INR "+i.subtotal.toFixed(2),480,11,bold);y-=22;
 line("Tax",365,11,regular,muted);line("INR "+i.taxTotal.toFixed(2),480,11,bold);y-=24;
 line("Total due at issue",365,12,bold);line("INR "+i.total.toFixed(2),475,12,bold);y-=35;
 if(i.notes){section("NOTES");paragraph(i.notes);}
 ensure(50);y-=8;horizontal();y-=20;
 line("Generated by DigiMarket. Verify issuer identity and applicable tax details.",m,8,regular,muted);
 doc.setTitle("Invoice "+(i.number??""));
 doc.setAuthor(i.sellerName);
 return doc.save();
}
